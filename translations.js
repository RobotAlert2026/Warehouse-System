(function () {
  const storageKey = 'sparepart_language';
  let language = localStorage.getItem(storageKey) || 'th';
  let translating = false;

  function translateText(text) {
    const value = text.trim();
    if (!value || language === 'th') return text;
    const direct = translations[language][value];
    if (direct) return text.replace(value, direct);
    return text
      .replace(/คงเหลือในคลัง/g, 'In stock')
      .replace(/คงเหลือ/g, 'Remaining')
      .replace(/ชิ้น/g, 'pcs')
      .replace(/รายการ/g, 'items')
      .replace(/ผู้เบิก:/g, 'Requester:')
      .replace(/เครื่องจักร:/g, 'Machine:')
      .replace(/วันที่:/g, 'Date:')
      .replace(/ขอเบิก:/g, 'Requested:')
      .replace(/เบิกแล้ว/g, 'Used')
      .replace(/แนะนำเติมอย่างน้อย/g, 'Recommended refill')
      .replace(/เติมสต็อก/g, 'Restock')
      .replace(/ครั้ง/g, 'times')
      .replace(/สำเร็จ/g, 'successfully');
  }

  function translatePage() {
    if (translating) return;
    translating = true;
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(node => {
      if (node.parentElement?.closest('script, style, input, textarea, select')) return;
      const translated = translateText(node.nodeValue);
      if (translated !== node.nodeValue) node.nodeValue = translated;
    });
    document.querySelectorAll('input[placeholder], [title]').forEach(element => {
      if (element.dataset.originalPlaceholder === undefined && element.placeholder) element.dataset.originalPlaceholder = element.placeholder;
      if (element.dataset.originalTitle === undefined && element.title) element.dataset.originalTitle = element.title;
      if (element.dataset.originalPlaceholder) element.placeholder = translateText(element.dataset.originalPlaceholder);
      if (element.dataset.originalTitle) element.title = translateText(element.dataset.originalTitle);
    });
    const button = document.getElementById('language-toggle');
    if (button) button.textContent = language === 'th' ? 'EN' : 'TH';
    translating = false;
  }

  window.toggleLanguage = function () {
    language = language === 'th' ? 'en' : 'th';
    localStorage.setItem(storageKey, language);
    window.location.reload();
  };

  window.initializeLanguage = function () {
    translatePage();
    new MutationObserver(translatePage).observe(document.body, { childList: true, subtree: true });
  };
})();
